<h1>О проекте</h1>
<p>PhotoHub — простая галерея изображений на PHP с поддержкой загрузки и автоматического создания миниатюр через GD.</p>
<ul>
  <li>Загрузка фото (JPEG, PNG, GIF, WebP)</li>
  <li>Ограничение размера файла — 10 МБ</li>
  <li>Автоматические квадратные миниатюры 200×200 px</li>
  <li>Безопасная отдача оригиналов через img.php</li>
</ul>

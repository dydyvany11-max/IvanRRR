<?php
// Задание 1: Условные операции — сравнение и выбор действия

$a = 17;
$b = -5;

// Если оба положительные — перемножить
// Если оба отрицательные — сложить модули
// Иначе — вычесть меньшее из большего

if ($a > 0 && $b > 0) {
    $result = $a * $b;
    $op = "произведение ({$a} × {$b})";
} elseif ($a < 0 && $b < 0) {
    $result = abs($a) + abs($b);
    $op = "сумма модулей (|{$a}| + |{$b}|)";
} else {
    $max = max($a, $b);
    $min = min($a, $b);
    $result = $max - $min;
    $op = "разность ({$max} − {$min})";
}

echo "a = {$a}, b = {$b}\n";
echo "Операция: {$op} = {$result}\n";
